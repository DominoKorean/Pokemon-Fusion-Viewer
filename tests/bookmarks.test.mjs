import test from 'node:test';
import assert from 'node:assert/strict';
import {bookmarkKey} from '../src/bookmarks.mjs';
test('autogenerated and unsuffixed custom images of the same pair keep separate bookmark identities',()=>{
  const auto={head:10,body:102,alt:'',custom:false},custom={...auto,custom:true};
  assert.notEqual(bookmarkKey(auto),bookmarkKey(custom));
  assert.equal(bookmarkKey(custom),bookmarkKey({...custom,variant:{id:'10.102'}}));
  assert.equal(bookmarkKey({head:10,body:102,variant:{id:'10.102'}}),bookmarkKey(custom));
});
test('official triple bookmarks have stable identities distinct from dual fusions',()=>{
  assert.equal(bookmarkKey({triple:'1.4.7'}),'triple:1.4.7');
  assert.notEqual(bookmarkKey({triple:'1.4.7'}),bookmarkKey({triple:'1.4.8'}));
});
